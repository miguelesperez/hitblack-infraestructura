CREATE DATABASE IF NOT EXISTS apuestas_db;
USE apuestas_db;
CREATE TABLE IF NOT EXISTS apuestas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT NOT NULL,
  usuario VARCHAR(50) NOT NULL,
  email VARCHAR(100) NOT NULL,
  partido_id INT NOT NULL,
  tipo ENUM('LOCAL','EMPATE','VISITANTE') NOT NULL,
  monto DECIMAL(12,2) NOT NULL,
  cuota DECIMAL(5,2) NOT NULL,
  ganancia_potencial DECIMAL(12,2) NOT NULL,
  fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
  estado ENUM('PENDIENTE','GANADA','PERDIDA') DEFAULT 'PENDIENTE'
);